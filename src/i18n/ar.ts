export function normalizeArabicText(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه');
}

export function resolveArabicSearchToken(query: string): string {
  const clean = query.trim();
  if (!clean || !/[\u0600-\u06FF]/.test(clean)) return clean;

  const normQ = normalizeArabicText(clean);

  for (const [code, ar] of Object.entries(SYRIAN_CITY_SHORT_AR)) {
    if (normalizeArabicText(ar).includes(normQ) || normQ.includes(normalizeArabicText(ar))) {
      return code;
    }
  }
  for (const [en, ar] of Object.entries(CITY_AR)) {
    if (normalizeArabicText(ar).includes(normQ)) {
      return en;
    }
  }
  for (const [en, ar] of Object.entries(AIRLINE_AR)) {
    if (normalizeArabicText(ar).includes(normQ)) {
      return en;
    }
  }
  return clean;
}

export function translateCountry(name?: string | null, compact = false): string {
  if (!name) return 'غير معروف';
  if (compact && (name === 'United Arab Emirates' || name === 'UAE')) return 'الإمارات';
  return COUNTRY_AR[name] ?? COUNTRY_AR_LOWER.get(name.trim().toLowerCase()) ?? name;
}

